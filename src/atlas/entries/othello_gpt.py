"""Othello-GPT's emergent world model: a linear "mine/theirs" board representation that can be edited.

Recomputes Li et al. 2023 (https://arxiv.org/abs/2210.13382; The Gradient essay https://thegradient.pub/othello/) and
Nanda, Lee, Wattenberg 2023 (https://arxiv.org/abs/2309.00941) on the open 8-layer Othello-GPT checkpoint
(TransformerLens ``othello-gpt``, trained only to predict legal next moves on synthetic random games):
- the model's top-1 move is legal (paper: illegal-move rate 0.01%);
- linear probes read the board as MINE / THEIRS / EMPTY (relative to the player who just moved) with ~99% accuracy from
  middle layers, while absolute BLACK / WHITE probes plateau far lower (paper: ~75%);
- controls: the same probes on a randomly initialised model, and with shuffled labels;
- intervention: flipping one square's probe direction in the residual stream changes the model's predicted legal moves
  to those of the edited board (paper: flip error 0.10 vs 2.72 for no intervention).
Games are generated by our engine (``atlas.common.othello``), matching the original synthetic dataset's rules.
"""

from __future__ import annotations

import copy
import time

import numpy as np
import torch

from ..common.io import verdict_row, write_entry
from ..common.log import get_logger
from ..common.models import hooked
from ..common.othello import SQ_TO_TOK, SQUARES, legal_moves, random_game
from ..common.stats import bootstrap_ci

log = get_logger()
SLUG = "othello-gpt"
N_CTX = 59


def make_games(n: int, seed: int):
    """n full-length random games (60 moves) -> tokens [n, 59], relative/absolute labels [n, 59, 64], legal sets."""
    rng = np.random.default_rng(seed)
    toks, rel, ab, legal, boards, mvs = [], [], [], [], [], []
    while len(toks) < n:
        moves, bs, movers, nxt = random_game(rng)
        if len(moves) < 60:
            continue
        toks.append([SQ_TO_TOK[m] for m in moves[:N_CTX]])
        b = np.stack(bs[:N_CTX]).reshape(N_CTX, 64)
        mv = np.array(movers[:N_CTX])[:, None]
        # Relative labels: 0 empty, 1 mine (mover's color), 2 theirs. Absolute: 0 empty, 1 black, 2 white.
        rel.append(np.where(b == 0, 0, np.where(b == mv, 1, 2)))
        ab.append(np.where(b == 0, 0, np.where(b == 1, 1, 2)))
        legal.append(nxt[:N_CTX])
        boards.append(bs[:N_CTX])
        mvs.append(movers[:N_CTX])
    return torch.tensor(toks), torch.tensor(np.array(rel)), torch.tensor(np.array(ab)), legal, boards, mvs


@torch.no_grad()
def resid(model, toks, device, bs=100):
    """Residual stream after each layer: list over layers 0..n_layers of [n, 59, d] (layer 0 = embeddings)."""
    outs = [[] for _ in range(model.cfg.n_layers + 1)]
    for i in range(0, len(toks), bs):
        _, cache = model.run_with_cache(toks[i : i + bs].to(device), names_filter=lambda n: "resid" in n)
        outs[0].append(cache["resid_pre", 0].half().cpu())
        for l in range(model.cfg.n_layers):
            outs[l + 1].append(cache["resid_post", l].half().cpu())
    return [torch.cat(o) for o in outs]


def train_probe(x_tr, y_tr, device, epochs=6, lr=1e-3, wd=0.01, seed=0):
    """Multinomial logistic probe: [d] -> [64 squares, 3 classes]. Returns (W [d, 64, 3], b [64, 3])."""
    torch.manual_seed(seed)
    d = x_tr.shape[-1]
    W = torch.zeros(d, 64, 3, device=device, requires_grad=True)
    b = torch.zeros(64, 3, device=device, requires_grad=True)
    opt = torch.optim.AdamW([W, b], lr=lr, weight_decay=wd)
    X, Y = x_tr.reshape(-1, d), y_tr.reshape(-1, 64)
    n = len(X)
    for _ in range(epochs):
        perm = torch.randperm(n)
        for i in range(0, n, 4096):
            idx = perm[i : i + 4096]
            xb, yb = X[idx].to(device).float(), Y[idx].to(device)
            logits = torch.einsum("nd,dsc->nsc", xb, W) + b
            loss = torch.nn.functional.cross_entropy(logits.reshape(-1, 3), yb.reshape(-1))
            opt.zero_grad()
            loss.backward()
            opt.step()
    return W.detach(), b.detach()


@torch.no_grad()
def probe_acc(W, b, x, y, device) -> float:
    d = x.shape[-1]
    X, Y = x.reshape(-1, d), y.reshape(-1, 64)
    correct = 0
    for i in range(0, len(X), 8192):
        logits = torch.einsum("nd,dsc->nsc", X[i : i + 8192].to(device).float(), W) + b
        correct += (logits.argmax(-1).cpu() == Y[i : i + 8192]).sum().item()
    return correct / Y.numel()


@torch.no_grad()
def legal_error(logits_row: torch.Tensor, legal: list[int]) -> int:
    """Li et al.'s error count: take the top-k predicted squares (k = #legal) and count mismatches with the legal set."""
    k = len(legal)
    if k == 0:
        return 0
    probs = logits_row[1:61]  # tokens 1..60
    top = {SQUARES[i] for i in probs.topk(k).indices.tolist()}
    return len(top.symmetric_difference(set(legal))) // 2


@torch.no_grad()
def intervene(model, toks, layer, pos, direction, scale_to, device):
    """Set the residual's component along ``direction`` (unit) at (layer resid_post, pos) to ``scale_to``; return logits at pos."""

    def hook(x, hook):
        c = x[:, pos] @ direction
        x[:, pos] = x[:, pos] + (scale_to - c)[:, None] * direction
        return x

    return model.run_with_hooks(toks.to(device), fwd_hooks=[(f"blocks.{layer}.hook_resid_post", hook)])[:, pos]


def compute(ctx) -> None:
    from transformer_lens import HookedTransformer

    t0 = time.time()
    model = hooked("othello-gpt", device=ctx.device)
    n_train, n_test = (600, 150) if ctx.quick else (3000, 500)
    toks, rel, ab, legal, boards, movers = make_games(n_train + n_test, ctx.seed)
    tr, te = slice(0, n_train), slice(n_train, None)

    # 1) Legality of top-1 predictions on test games.
    with torch.no_grad():
        logits = torch.cat([model(toks[te][i : i + 100].to(ctx.device)).cpu() for i in range(0, n_test, 100)])
    top1 = logits[..., 1:61].argmax(-1)
    illegal = np.mean([SQUARES[int(top1[g, p])] not in legal[n_train + g][p] for g in range(n_test) for p in range(N_CTX) if legal[n_train + g][p]])
    log.info("othello: top-1 illegal-move rate %.4f", illegal)

    # 2) Probes per layer: relative, absolute, shuffled-label control, random-init model control.
    R = resid(model, toks, ctx.device)
    # Pretrained configs carry init_weights=False (weights would stay uninitialized/zero); enable initialisation.
    rand_cfg = copy.deepcopy(model.cfg)
    rand_cfg.init_weights = True
    rand = HookedTransformer(rand_cfg).to(ctx.device).eval()
    Rr = resid(rand, toks, ctx.device)
    g = torch.Generator().manual_seed(0)
    shuf = rel[tr].reshape(-1, 64)[torch.randperm(n_train * N_CTX, generator=g)].reshape(rel[tr].shape)
    acc = {k: [] for k in ("mine/theirs", "black/white", "random-init model", "shuffled labels")}
    probes = []
    for l in range(len(R)):
        W, b = train_probe(R[l][tr], rel[tr], ctx.device)
        probes.append((W, b))
        acc["mine/theirs"].append(probe_acc(W, b, R[l][te], rel[te], ctx.device))
        W2, b2 = train_probe(R[l][tr], ab[tr], ctx.device)
        acc["black/white"].append(probe_acc(W2, b2, R[l][te], ab[te], ctx.device))
        W3, b3 = train_probe(Rr[l][tr], rel[tr], ctx.device)
        acc["random-init model"].append(probe_acc(W3, b3, Rr[l][te], rel[te], ctx.device))
        W4, b4 = train_probe(R[l][tr], shuf, ctx.device)
        acc["shuffled labels"].append(probe_acc(W4, b4, R[l][te], rel[te], ctx.device))
        log.info("layer %d probe acc: %s", l, {k: round(v[-1], 4) for k, v in acc.items()})
    # Empty-square accuracy is trivial-ish; report accuracy on occupied squares only as the headline metric.
    occ_acc = []
    for l in range(len(R)):
        W, b = probes[l]
        X = R[l][te].reshape(-1, R[l].shape[-1]).to(ctx.device).float()
        pred = (torch.einsum("nd,dsc->nsc", X, W) + b).argmax(-1).cpu()
        Y = rel[te].reshape(-1, 64)
        mask = Y != 0
        occ_acc.append(((pred == Y) & mask).sum().item() / mask.sum().item())
    # Bootstrap CIs over test games at the best layer (review follow-ups, M8): all squares and occupied squares only.
    bl = int(np.argmax(acc["mine/theirs"]))
    with torch.no_grad():
        Wb, bb = probes[bl]
        pg = (torch.einsum("gpd,dsc->gpsc", R[bl][te].to(ctx.device).float(), Wb) + bb).argmax(-1).cpu()  # [game, pos, square]
    Yg = rel[te]
    hit = (pg == Yg).float()
    acc_ci = bootstrap_ci(hit.mean((1, 2)).numpy())
    occ_ci = bootstrap_ci((((pg == Yg) & (Yg != 0)).sum((1, 2)) / (Yg != 0).sum((1, 2))).numpy())

    # 3) Intervention: flip one occupied square's mine/theirs probe direction at the best middle layer (3–5).
    L = 3 + int(np.argmax(acc["mine/theirs"][4:7]))  # resid_post of block L == R[L+1]
    W, b = probes[L + 1]
    rng = np.random.default_rng(ctx.seed)
    errs = {"intervention": [], "no intervention": [], "random direction": []}
    examples = []
    tried = 0
    while len(errs["intervention"]) < (30 if ctx.quick else 150) and tried < 5000:
        tried += 1
        gi = int(rng.integers(n_train, n_train + n_test))
        p = int(rng.integers(10, 50))
        board = boards[gi][p]
        mover = movers[gi][p]
        nxt = -mover if legal_moves(board, -mover) else mover
        occ = [s for s in range(64) if board.reshape(-1)[s] != 0 and s not in (27, 28, 35, 36)]
        s = int(rng.choice(occ))
        edited = board.copy().reshape(-1)
        edited[s] = -edited[s]
        edited = edited.reshape(8, 8)
        new_legal = legal_moves(edited, nxt)
        if set(new_legal) == set(legal_moves(board, nxt)) or not new_legal:
            continue  # only test flips that change the legal-move set
        cur = int(rel[gi, p, s])  # 1 mine, 2 theirs
        tgt = 3 - cur
        d = W[:, s, tgt] - W[:, s, cur]
        d = d / d.norm()
        with torch.no_grad():
            _, cache = model.run_with_cache(toks[gi : gi + 1].to(ctx.device), names_filter=f"blocks.{L}.hook_resid_post")
            c = (cache[f"blocks.{L}.hook_resid_post"][0, p] @ d).item()
        lg = intervene(model, toks[gi : gi + 1], L, p, d, -c, ctx.device)[0].cpu()
        base = logits_for(model, toks[gi : gi + 1], p, ctx.device)
        rd = torch.randn_like(d)
        rd = rd / rd.norm()
        with torch.no_grad():
            cr = (cache[f"blocks.{L}.hook_resid_post"][0, p] @ rd).item()
        lr_ = intervene(model, toks[gi : gi + 1], L, p, rd, cr - 2 * c, ctx.device)[0].cpu()
        errs["intervention"].append(legal_error(lg, new_legal))
        errs["no intervention"].append(legal_error(base, new_legal))
        errs["random direction"].append(legal_error(lr_, new_legal))
        if len(examples) < 6:
            examples.append(
                {
                    "board": (board.reshape(-1) * mover).tolist(),  # +1 = mover's discs
                    "square": s,
                    "legal_before": legal_moves(board, nxt),
                    "legal_after": new_legal,
                    "probs_before": base[1:61].softmax(-1).numpy(),
                    "probs_after": lg[1:61].softmax(-1).numpy(),
                }
            )
    err_mean = {k: float(np.mean(v)) for k, v in errs.items()}
    log.info("othello intervention at layer %d: %s (n=%d)", L, err_mean, len(errs["intervention"]))

    # 4) Viz payload: two test games, probe predictions at layers 0/2/4/6/8 for each move, model move probabilities.
    show_layers = [0, 2, 4, 6, 8]
    games = []
    for gi in (n_train, n_train + 1):
        with torch.no_grad():
            mp = model(toks[gi : gi + 1].to(ctx.device))[0, :, 1:61].softmax(-1).cpu().numpy()
        probe_pred = {}
        for l in show_layers:
            W_, b_ = probes[l]
            pr = (torch.einsum("pd,dsc->psc", R[l][gi].to(ctx.device).float(), W_) + b_).softmax(-1).cpu().numpy()
            probe_pred[str(l)] = np.round(pr[..., 1] - pr[..., 2], 2)  # P(mine) - P(theirs) per square
        games.append(
            {
                "moves": [SQUARES[t - 1] for t in toks[gi].tolist()],
                "rel": rel[gi].numpy(),
                "legal": legal[gi],
                "move_probs": np.round(mp, 3),
                "probe": probe_pred,
            }
        )
    best = int(np.argmax(acc["mine/theirs"]))
    summary = {
        "illegal_rate": float(illegal),
        "best_layer": best,
        "acc_rel_best": acc["mine/theirs"][best],
        "acc_abs_best": float(max(acc["black/white"])),
        "acc_rand_best": float(max(acc["random-init model"])),
        "acc_shuf_best": float(max(acc["shuffled labels"])),
        "occ_acc_best": float(max(occ_acc)),
        "int_layer": L,
        "err_int": err_mean["intervention"],
        "err_null": err_mean["no intervention"],
        "err_rand": err_mean["random direction"],
        "n_int": len(errs["intervention"]),
        "n_games_train": n_train,
        "n_games_test": n_test,
    }
    repl = [
        verdict_row(
            "Othello-GPT predicts legal moves",
            "illegal top-1 rate 0.01% (Li et al.)",
            f"{illegal * 100:.2f}% illegal top-1 moves on {n_test} held-out synthetic games",
            "< 1%",
            illegal < 0.01,
        ),
        verdict_row(
            "The board is linearly decodable relative to the current player",
            "linear mine/theirs probes ≈ 99.5% from layer 4; black/white ≈ 75% (Nanda et al.)",
            f"mine/theirs {acc['mine/theirs'][best] * 100:.1f}% [{acc_ci[1] * 100:.1f}, {acc_ci[2] * 100:.1f}] (best layer {best}; occupied squares only "
            f"{occ_acc[best] * 100:.1f}% [{occ_ci[1] * 100:.1f}, {occ_ci[2] * 100:.1f}]; 95% CIs over test games); black/white {max(acc['black/white']) * 100:.1f}%; "
            f"random-init model {max(acc['random-init model']) * 100:.1f}%; shuffled labels {max(acc['shuffled labels']) * 100:.1f}%",
            "mine/theirs > 95% and ≥ 10 points above black/white, random-init and shuffled-label controls",
            acc["mine/theirs"][best] > 0.95
            and acc["mine/theirs"][best] - max(max(acc["black/white"]), max(acc["random-init model"]), max(acc["shuffled labels"])) >= 0.10,
        ),
        verdict_row(
            "Editing the linear board representation changes predicted legal moves",
            "flip error 0.10 (linear) vs 2.72 (no intervention) (Nanda et al. Table)",
            f"layer {L}: error {err_mean['intervention']:.2f} vs {err_mean['no intervention']:.2f} without intervention and "
            f"{err_mean['random direction']:.2f} for a random direction (n = {len(errs['intervention'])})",
            "intervention error < 50% of the no-intervention error and below the random-direction error",
            err_mean["intervention"] < 0.5 * err_mean["no intervention"] and err_mean["intervention"] < err_mean["random direction"],
            partial=err_mean["intervention"] < err_mean["no intervention"],
        ),
    ]
    payload = {"acc": acc, "occ_acc": occ_acc, "games": games, "show_layers": show_layers, "examples": examples, "errs": errs}
    write_entry(SLUG, payload, summary, repl, models=["othello-gpt"], runtime_s=time.time() - t0, ndigits=3)
    log.info("othello summary: %s", summary)


@torch.no_grad()
def logits_for(model, toks, pos, device):
    return model(toks.to(device))[0, pos].cpu()
