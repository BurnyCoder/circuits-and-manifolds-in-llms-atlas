"""Indirect Object Identification (IOI) circuit in GPT-2 small.

Recomputes the core claims of Wang et al. 2022, "Interpretability in the Wild" (https://arxiv.org/abs/2211.00593):
GPT-2 small completes "When Mary and John went to the store, John gave a drink to" with " Mary" (the indirect object,
IO) rather than " John" (the subject, S), using 26 heads in 7 classes (paper Fig. 2). We measure:
- the baseline logit difference logit(IO) - logit(S) at the END token (paper: 3.56, IO > S in 99.3% of prompts);
- per-head importance: direct logit attribution (DLA) onto W_U[IO] - W_U[S], and activation "noising" (replace a
  head's output with its output on the p_ABC corrupted dataset, where all three names are different);
- name-mover attention from END to IO vs S (paper: name movers attend to IO, mean 0.59);
- mean-ablation of every one of the 2^7 = 128 combinations of the 7 head classes (ablation value = mean output over
  p_ABC prompts of the same template, position by position, as in the paper's knockouts, §4);
- faithfulness: keep only the 26 circuit heads (mean-ablate the other 118) -> fraction of logit diff kept (paper: 87%);
- control: mean-ablate random head sets of the same size as the circuit.
Templates/names are our own, in the paper's style (BABA/ABBA orderings), filtered to single GPT-2 tokens so
positions align within a template.
"""

from __future__ import annotations

import itertools
import time

import numpy as np
import torch

from ..common.io import verdict_row, write_entry
from ..common.log import get_logger
from ..common.models import hooked
from ..common.stats import bootstrap_ci, ci_str

log = get_logger()
SLUG = "ioi"

# Head classes from Wang et al. 2022, Fig. 2 (layer.head).
CLASSES: dict[str, list[tuple[int, int]]] = {
    "Previous token": [(2, 2), (4, 11)],
    "Duplicate token": [(0, 1), (3, 0), (0, 10)],
    "Induction": [(5, 5), (6, 9), (5, 8), (5, 9)],
    "S-inhibition": [(7, 3), (7, 9), (8, 6), (8, 10)],
    "Name mover": [(9, 9), (9, 6), (10, 0)],
    "Negative name mover": [(10, 7), (11, 10)],
    "Backup name mover": [(9, 0), (9, 7), (10, 1), (10, 2), (10, 6), (10, 10), (11, 2), (11, 9)],
}
CIRCUIT = sorted({h for hs in CLASSES.values() for h in hs})

# {A}=IO, {B}=S. BABA-style templates (S mentioned first) and ABBA (IO first) are both generated by name order.
TEMPLATES = [
    "When {X} and {Y} went to the {P}, {B} gave a {O} to",
    "Then, {X} and {Y} went to the {P}. {B} gave a {O} to",
    "After {X} and {Y} went to the {P}, {B} gave a {O} to",
    "While {X} and {Y} were working at the {P}, {B} gave a {O} to",
    "When {X} and {Y} got a {O} at the {P}, {B} decided to give it to",
    "Friends {X} and {Y} went to the {P}. {B} gave a {O} to",
    "Then, {X} and {Y} had a long day at the {P}. {B} gave a {O} to",
    "The {P} was busy when {X} and {Y} arrived. {B} handed a {O} to",
]
NAMES = """Mary John Tom James Dan Sid Martin Amy Kate Paul Mark Sarah Lisa Anna David Michael Robert Laura Emma Jack
Alex Sam Ben Max Lucy Rose Grace Henry Peter Adam Eric Jane Chris Kevin Ryan Jason Brian Steve Tim Alice""".split()
PLACES = "store park school office restaurant hospital station house garden library beach market".split()
OBJECTS = "drink book ring bone computer necklace kiss gift letter ball snack basket".split()


def _single_tokens(model, words: list[str]) -> list[str]:
    """Keep words that are a single GPT-2 token with a leading space (so all templates align position-wise)."""
    return [w for w in words if len(model.to_tokens(" " + w, prepend_bos=False)[0]) == 1]


def build_dataset(model, n_per_template: int, seed: int):
    """Clean IOI prompts + matching p_ABC corrupted prompts, grouped by template (positions identical within group)."""
    rng = np.random.default_rng(seed)
    names, places, objs = (_single_tokens(model, w) for w in (NAMES, PLACES, OBJECTS))
    groups = []
    for ti, tpl in enumerate(TEMPLATES):
        clean, corrupt, io_ids, s_ids = [], [], [], []
        for k in range(n_per_template):
            io, s, c1, c2, c3 = rng.choice(names, 5, replace=False)
            p, o = rng.choice(places), rng.choice(objs)
            x, y = (s, io) if k % 2 == 0 else (io, s)  # alternate BABA / ABBA
            clean.append(tpl.format(X=x, Y=y, B=s, P=p, O=o))
            # p_ABC: the three name slots get three different names, unrelated to IO/S (Wang et al. §3).
            corrupt.append(tpl.format(X=c1, Y=c2, B=c3, P=p, O=o))
            io_ids.append(model.to_single_token(" " + io))
            s_ids.append(model.to_single_token(" " + s))
        tc, tx = model.to_tokens(clean), model.to_tokens(corrupt)
        assert tc.shape == tx.shape, f"template {ti} misaligned"
        groups.append({"tpl": tpl, "clean": tc, "corrupt": tx, "io": torch.tensor(io_ids), "s": torch.tensor(s_ids), "texts": clean})
    return groups


def logit_diff(logits: torch.Tensor, io: torch.Tensor, s: torch.Tensor) -> torch.Tensor:
    """logit(IO) - logit(S) at the last position, per prompt."""
    last = logits[:, -1]
    idx = torch.arange(len(io))
    return last[idx, io.to(last.device)] - last[idx, s.to(last.device)]


def _mean_z(model, toks: torch.Tensor) -> list[torch.Tensor]:
    """Per-layer mean head output hook_z over a batch: list of [pos, heads, d_head]."""
    _, cache = model.run_with_cache(toks, names_filter=lambda n: n.endswith("attn.hook_z"))
    return [cache["z", l].mean(0) for l in range(model.cfg.n_layers)]


def _run_ablated(model, toks, heads: list[tuple[int, int]], means: list[torch.Tensor] | None, replace: list[torch.Tensor] | None = None):
    """Forward pass with the given heads' outputs (hook_z, [batch, pos, head, d_head]) overwritten.

    ``means``: per-layer [pos, head, d_head] mean-ablation values (broadcast over the batch);
    ``replace``: per-layer [batch, pos, head, d_head] activations from another run (activation patching).
    """
    by_layer: dict[int, list[int]] = {}
    for l, h in heads:
        by_layer.setdefault(l, []).append(h)

    def make_hook(layer: int, hs: list[int]):
        src = replace[layer] if replace is not None else means[layer][None]  # [batch or 1, pos, head, d_head]

        def hook(z, hook):
            z[:, :, hs] = src[:, :, hs]  # broadcasting handles the mean case
            return z

        return hook

    hooks = [(f"blocks.{l}.attn.hook_z", make_hook(l, hs)) for l, hs in by_layer.items()]
    return model.run_with_hooks(toks, fwd_hooks=hooks)


@torch.no_grad()
def compute(ctx) -> None:
    t0 = time.time()
    model = hooked("gpt2", device=ctx.device)
    groups = build_dataset(model, 6 if ctx.quick else 40, ctx.seed)
    nL, nH = model.cfg.n_layers, model.cfg.n_heads

    ld_clean, ld_abc, io_win = [], [], []
    dla = torch.zeros(nL, nH)
    noise = torch.zeros(nL, nH)
    nm_attn = {f"{l}.{h}": {"IO": [], "S1": [], "S2": []} for l, h in CLASSES["Name mover"] + CLASSES["Negative name mover"]}
    combos = list(itertools.product([0, 1], repeat=len(CLASSES)))
    combo_ld = np.zeros(len(combos))
    faithful, rand_ld = [], []
    rng = np.random.default_rng(ctx.seed)
    rand_sets = [
        [divmod(int(i), nH) for i in rng.choice(nL * nH, size=len(CIRCUIT), replace=False)] for _ in range(10 if ctx.quick else 40)
    ]
    rand_acc = np.zeros(len(rand_sets))
    n_total = 0
    example = None
    for g in groups:
        tc, tx = g["clean"].to(ctx.device), g["corrupt"].to(ctx.device)
        io, s = g["io"], g["s"]
        n = len(io)
        n_total += n
        logits, cache = model.run_with_cache(tc)
        ld = logit_diff(logits, io, s)
        ld_clean.append(ld.cpu())
        io_win.append((ld > 0).float().cpu())
        ld_abc.append(logit_diff(model(tx), io, s).cpu())

        # Direct logit attribution of each head onto (W_U[IO] - W_U[S]) at END, through the final LayerNorm scale.
        z = torch.stack([cache["z", l][:, -1] for l in range(nL)], 1)  # [n, L, H, d_head]
        head_out = torch.einsum("nlhd,lhdm->nlhm", z, model.W_O)  # [n, L, H, d_model]
        scale = cache["ln_final.hook_scale"][:, -1]  # [n, 1]
        direction = model.W_U[:, io.to(ctx.device)].T - model.W_U[:, s.to(ctx.device)].T  # [n, d_model]
        dla += torch.einsum("nlhm,nm->lh", head_out / scale[:, None, None], direction).cpu()

        # Name-mover attention from END to IO, S1, S2 token positions.
        toks0 = tc[0].tolist()
        pos_io = [toks0.index(int(io[0]))]
        s_pos = [i for i, t in enumerate(toks0) if t == int(s[0])]
        for key in nm_attn:
            l, h = map(int, key.split("."))
            pat = cache["pattern", l][:, h, -1]  # [n, src]
            # Per prompt the IO/S positions are template-fixed; locate them per prompt for safety.
            for i in range(n):
                ti = tc[i].tolist()
                p_io = ti.index(int(io[i]))
                p_s = [j for j, t in enumerate(ti) if t == int(s[i])]
                nm_attn[key]["IO"].append(pat[i, p_io].item())
                nm_attn[key]["S1"].append(pat[i, p_s[0]].item())
                nm_attn[key]["S2"].append(pat[i, p_s[-1]].item())
        if example is None:
            example = {
                "text": g["texts"][0],
                "tokens": [model.tokenizer.decode([t]) for t in toks0],
                "io_pos": pos_io[0],
                "s_pos": s_pos,
                "end_attn": {k: cache["pattern", int(k.split(".")[0])][0, int(k.split(".")[1]), -1].cpu().numpy() for k in nm_attn},
            }

        # Activation noising per head: replace head output with its p_ABC output (all positions).
        _, cache_x = model.run_with_cache(tx, names_filter=lambda nme: nme.endswith("attn.hook_z"))
        zx = [cache_x["z", l] for l in range(nL)]
        for l in range(nL):
            for h in range(nH):
                noise[l, h] += (logit_diff(_run_ablated(model, tc, [(l, h)], None, replace=zx), io, s) - ld).sum().cpu()

        # Mean-ablation over all 128 class combinations (means from p_ABC of the same template).
        means = _mean_z(model, tx)
        for ci, mask in enumerate(combos):
            heads = [h for on, hs in zip(mask, CLASSES.values()) if on for h in hs]
            combo_ld[ci] += logit_diff(_run_ablated(model, tc, heads, means), io, s).sum().item() if heads else ld.sum().item()
        non_circuit = [(l, h) for l in range(nL) for h in range(nH) if (l, h) not in CIRCUIT]
        faithful.append(logit_diff(_run_ablated(model, tc, non_circuit, means), io, s).cpu())
        for ri, rs in enumerate(rand_sets):
            rand_acc[ri] += logit_diff(_run_ablated(model, tc, rs, means), io, s).sum().item()
        log.info("IOI template done: %s (mean logit diff %.2f)", g["tpl"], ld.mean().item())

    ld_clean = torch.cat(ld_clean).numpy()
    ld_abc = torch.cat(ld_abc).numpy()
    io_win = torch.cat(io_win).numpy()
    faithful = torch.cat(faithful).numpy()
    dla, noise = (dla / n_total).numpy(), (noise / n_total).numpy()
    combo_ld /= n_total
    rand_ld = rand_acc / n_total
    full = bootstrap_ci(ld_clean)
    circ = bootstrap_ci(faithful)
    all_ablated = combo_ld[-1]  # every class ablated
    nm = {k: {kk: float(np.mean(v)) for kk, v in d.items()} for k, d in nm_attn.items()}
    nm_io = np.mean([nm[f"{l}.{h}"]["IO"] for l, h in CLASSES["Name mover"]])
    nm_s = np.mean([max(nm[f"{l}.{h}"]["S1"], nm[f"{l}.{h}"]["S2"]) for l, h in CLASSES["Name mover"]])
    neg_dla = [float(dla[l, h]) for l, h in CLASSES["Negative name mover"]]

    summary = {
        "n_prompts": int(n_total),
        "ld_clean": full[0],
        "ld_clean_lo": full[1],
        "ld_clean_hi": full[2],
        "ld_abc": float(ld_abc.mean()),
        "io_win": float(io_win.mean()),
        "faithful_ld": circ[0],
        "faithful_frac": circ[0] / full[0],
        "all_classes_ablated_ld": float(all_ablated),
        "rand_ablated_ld_median": float(np.median(rand_ld)),
        "nm_attn_io": float(nm_io),
        "nm_attn_s": float(nm_s),
        "neg_nm_dla_10_7": neg_dla[0],
        "neg_nm_dla_11_10": neg_dla[1],
        "top_dla_head": "{}.{}".format(*np.unravel_index(dla.argmax(), dla.shape)),
    }
    repl = [
        verdict_row(
            "GPT-2 small prefers the indirect object over the subject",
            "mean logit diff 3.56; IO > S in 99.3% of prompts",
            f"{ci_str(*full)} on {n_total} prompts; IO > S in {io_win.mean() * 100:.1f}%",
            "mean logit diff > 2 and IO > S in > 90% of prompts",
            full[0] > 2 and io_win.mean() > 0.9,
        ),
        verdict_row(
            "Name movers (9.9, 9.6, 10.0) attend from END to the indirect object",
            "mean attention to IO 0.59 (§3.1)",
            f"mean attention to IO {nm_io:.2f} vs to S {nm_s:.2f}",
            "attention to IO > 2× attention to S",
            nm_io > 2 * nm_s,
        ),
        verdict_row(
            "Negative name movers (10.7, 11.10) write against the answer",
            "negative copy score 98% (§3.4)",
            f"direct logit attribution {neg_dla[0]:.2f} and {neg_dla[1]:.2f}",
            "both heads have negative DLA on logit(IO) − logit(S)",
            all(d < 0 for d in neg_dla),
        ),
        verdict_row(
            "The 26-head circuit is faithful",
            "circuit keeps 87% of the logit difference (§4)",
            f"circuit-only logit diff {ci_str(*circ)} = {circ[0] / full[0] * 100:.0f}% of full model",
            "between 60% and 120% of the full model",
            0.6 <= circ[0] / full[0] <= 1.2,
            partial=0.4 <= circ[0] / full[0] < 0.6,
        ),
        verdict_row(
            "Knocking out the circuit breaks the task; random heads don't",
            "circuit knockouts collapse performance; random heads matter little (§4)",
            f"all 7 classes ablated → {all_ablated:.2f}; {len(CIRCUIT)} random heads → median {np.median(rand_ld):.2f}",
            "circuit knockout drops logit diff by > 70%, random median drops it by < 40%",
            all_ablated < 0.3 * full[0] and np.median(rand_ld) > 0.6 * full[0],
        ),
    ]
    payload = {
        "classes": {k: [f"{l}.{h}" for l, h in v] for k, v in CLASSES.items()},
        "dla": dla,
        "noise": noise,
        "combos": [{"mask": list(m), "ld": float(v)} for m, v in zip(combos, combo_ld)],
        "rand_ablated": rand_ld,
        "nm_attn": nm,
        "example": example,
        "ld_hist": np.histogram(ld_clean, bins=30)[0].tolist(),
        "ld_hist_edges": np.histogram(ld_clean, bins=30)[1].tolist(),
    }
    write_entry(SLUG, payload, summary, repl, models=["gpt2"], runtime_s=time.time() - t0)
    log.info("IOI summary: %s", summary)
