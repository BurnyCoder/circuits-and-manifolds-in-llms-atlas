"""Check every http(s) link cited in README, docs, reports and site entry pages; write reports/linkcheck.md.

Local context: GET with a generic user agent (some hosts reject HEAD), redirects followed, 20 s timeout, 8 threads.
A link is "ok" for status < 400; 403/429 are reported separately because many publishers block scripted requests
even when the page exists (those are checked by hand). Global context: part of the fact-check pass before release.

Usage: ``uv run python -m atlas.linkcheck``
"""

from __future__ import annotations

import re
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor

import requests

from .common.env import ROOT

SOURCES = ["README.md", "docs", "reports", "site/src/content/entries"]
URL_RE = re.compile(r"https?://[^\s<>\"'`)\]|]+")
HEADERS = {"User-Agent": "Mozilla/5.0 (compatible; atlas-linkcheck/1.0)"}
# Links that are templates or local-only, not real citations.
SKIP = ("localhost", "127.0.0.1", "example.com")


def collect() -> dict[str, set[str]]:
    """Map URL -> set of files citing it."""
    found: dict[str, set[str]] = defaultdict(set)
    for src in SOURCES:
        path = ROOT / src
        files = [path] if path.is_file() else [p for p in path.rglob("*.md")]
        for f in files:
            if f.name == "linkcheck.md":
                continue
            for url in URL_RE.findall(f.read_text(encoding="utf-8")):
                url = url.rstrip(".,;:")
                if not any(s in url for s in SKIP):
                    found[url].add(str(f.relative_to(ROOT)).replace("\\", "/"))
    return found


def status(url: str) -> tuple[str, int | str]:
    try:
        r = requests.get(url, headers=HEADERS, timeout=20, allow_redirects=True, stream=True)
        r.close()
        return url, r.status_code
    except requests.RequestException as e:
        return url, type(e).__name__


def main() -> None:
    found = collect()
    with ThreadPoolExecutor(8) as ex:
        results = dict(ex.map(status, sorted(found)))
    bad = {u: s for u, s in results.items() if not (isinstance(s, int) and s < 400)}
    blocked = {u: s for u, s in bad.items() if s in (401, 403, 429)}
    broken = {u: s for u, s in bad.items() if u not in blocked}
    lines = [
        "# Link check",
        "",
        f"Generated by `uv run python -m atlas.linkcheck`. {len(results)} unique URLs; {len(broken)} broken or "
        f"unreachable; {len(blocked)} blocked for scripts (401/403/429, checked by hand).",
        "",
        "## Broken / unreachable",
        "",
        "| URL | Status | Cited in |",
        "|---|---|---|",
    ]
    lines += [f"| {u} | {s} | {', '.join(sorted(found[u]))} |" for u, s in sorted(broken.items())]
    lines += ["", "## Blocked for scripts", "", "| URL | Status | Cited in |", "|---|---|---|"]
    lines += [f"| {u} | {s} | {', '.join(sorted(found[u]))} |" for u, s in sorted(blocked.items())]
    (ROOT / "reports" / "linkcheck.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(results)} URLs, {len(broken)} broken, {len(blocked)} blocked -> reports/linkcheck.md")


if __name__ == "__main__":
    main()
