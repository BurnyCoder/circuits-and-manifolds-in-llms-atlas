"""Run atlas entries on a rented RunPod GPU with a hard spending cap (default $20 in total, across all sessions).

Local context:
- Budget guard: every session is appended to ``results/runpod/spend.json`` (price/h × uptime). A launch is refused if
  logged spend + price × ``--max-hours`` would exceed ``--budget``. The pod is terminated in ``finally`` (also on
  Ctrl-C / errors) and at ``--max-hours`` at the latest.
- No credentials leave this machine: the pod clones the public repo and runs ``src/atlas/runpod/remote.sh``, which
  serves status and ``results.tar.gz`` on port 8000 through RunPod's HTTP proxy (https://{pod_id}-8000.proxy.runpod.net,
  https://docs.runpod.io/pods/configuration/expose-ports). We download the results, unpack them into the repo, terminate.
- GPU choice: the cheapest available type with ≥ ``--min-vram`` GB among a short list (prices from the RunPod API).
SDK: runpod-python (https://github.com/runpod/runpod-python) — create_pod / get_pod / get_gpu / terminate_pod.
Global context: the paper-scale tier of the plan (6–8B models that do not fit the 8 GB laptop GPU).

Usage: ``uv run python -m atlas.runpod.launch --entries number_helix --set helix_models=EleutherAI/gpt-j-6b --max-hours 2``
"""

from __future__ import annotations

import argparse
import io
import json
import os
import tarfile
import time
from datetime import datetime, timezone

import requests

from ..common.env import RESULTS, ROOT, setup
from ..common.log import get_logger

LEDGER = RESULTS / "runpod" / "spend.json"
REPORT = ROOT / "reports" / "runpod-spend.md"
IMAGE = "runpod/pytorch:2.4.0-py3.11-cuda12.4.1-devel-ubuntu22.04"  # has git, curl, python3; uv brings its own Python
GPU_CANDIDATES = ["NVIDIA GeForce RTX 4090", "NVIDIA RTX A5000", "NVIDIA L4", "NVIDIA RTX A6000", "NVIDIA L40S", "NVIDIA A40"]
REPO = "https://github.com/BurnyCoder/circuits-and-manifolds-in-llms-atlas"


def ledger() -> list[dict]:
    return json.loads(LEDGER.read_text(encoding="utf-8")) if LEDGER.exists() else []


def spent() -> float:
    return float(sum(s.get("cost", 0.0) for s in ledger()))


def record(session: dict) -> None:
    """Append/replace a session in the ledger and regenerate reports/runpod-spend.md."""
    rows = [s for s in ledger() if s["pod_id"] != session["pod_id"]] + [session]
    LEDGER.parent.mkdir(parents=True, exist_ok=True)
    LEDGER.write_text(json.dumps(rows, indent=1), encoding="utf-8")
    lines = ["# RunPod spend", "", "Generated by `atlas.runpod.launch` from `results/runpod/spend.json`. Budget cap: $20 total.", "",
             "| Pod | GPU | $/h | Start (UTC) | Hours | Cost ($) | Entries | Outcome |", "|---|---|---|---|---|---|---|---|"]
    for s in rows:
        lines.append(f"| {s['pod_id']} | {s['gpu']} | {s['price']:.3f} | {s['start']} | {s['hours']:.2f} | {s['cost']:.2f} | {s['entries']} | {s.get('outcome', '')} |")
    lines.append(f"| **Total** | | | | | **{sum(s['cost'] for s in rows):.2f}** | | |")
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def cheapest_gpu(min_vram: int, cloud: str) -> tuple[str, float]:
    """(gpu_type_id, $/h) of the cheapest candidate with enough memory and a listed price for the chosen cloud."""
    import runpod

    best = None
    for gid in GPU_CANDIDATES:
        try:
            g = runpod.get_gpu(gid)
        except Exception:
            continue
        if (g.get("memoryInGb") or 0) < min_vram:
            continue
        price = g.get("communityPrice") if cloud == "COMMUNITY" else g.get("securePrice")
        if price and (best is None or price < best[1]):
            best = (gid, float(price))
    if best is None:
        raise SystemExit("no candidate GPU with a listed price; try --cloud SECURE or another --min-vram")
    return best


def main(argv: list[str] | None = None) -> None:
    setup()
    import runpod

    log = get_logger("runpod")
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--entries", required=True)
    p.add_argument("--set", action="append", default=[], help="key=value overrides passed to atlas.run")
    p.add_argument("--ref", default="main", help="git ref to run on the pod (must be pushed)")
    p.add_argument("--max-hours", type=float, default=2.0)
    p.add_argument("--budget", type=float, default=20.0)
    p.add_argument("--min-vram", type=int, default=24)
    p.add_argument("--cloud", default="COMMUNITY", choices=["COMMUNITY", "SECURE"])
    p.add_argument("--dry-run", action="store_true", help="pick GPU and check the budget, launch nothing")
    a = p.parse_args(argv)

    key = os.environ.get("RUNPOD_API_KEY")
    if not key:
        raise SystemExit("RUNPOD_API_KEY missing in .env")
    runpod.api_key = key
    gpu, price = cheapest_gpu(a.min_vram, a.cloud)
    already = spent()
    worst = price * a.max_hours
    log.info("GPU %s at $%.3f/h; spent so far $%.2f; this session at most $%.2f (cap $%.2f)", gpu, price, already, worst, a.budget)
    if already + worst > a.budget:
        raise SystemExit(f"refusing: ${already:.2f} spent + ${worst:.2f} worst case > ${a.budget:.2f} budget")
    if a.dry_run:
        return

    cmd = f"bash -c 'git clone -q {REPO} /w/repo && bash /w/repo/src/atlas/runpod/remote.sh'"
    pod = runpod.create_pod(
        name="atlas-paper-scale", image_name=IMAGE, gpu_type_id=gpu, cloud_type=a.cloud, gpu_count=1,
        container_disk_in_gb=80, volume_in_gb=0, ports="8000/http", docker_args=cmd, start_ssh=False,
        env={"ATLAS_ENTRIES": a.entries, "ATLAS_SET": " ".join(a.set), "ATLAS_REF": a.ref},
    )
    pod_id = pod["id"]
    t0 = time.time()
    session = {"pod_id": pod_id, "gpu": gpu, "price": price, "start": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"),
               "hours": 0.0, "cost": 0.0, "entries": a.entries, "outcome": "running"}
    record(session)
    base = f"https://{pod_id}-8000.proxy.runpod.net"
    try:
        status = ""
        while time.time() - t0 < a.max_hours * 3600:
            time.sleep(60)
            session["hours"] = (time.time() - t0) / 3600
            session["cost"] = session["hours"] * price
            record(session)  # keep the ledger current even if this process dies
            try:
                status = requests.get(f"{base}/status.txt", timeout=20).text.strip()
            except requests.RequestException:
                status = "unreachable"
            log.info("pod %s: %s (%.2f h, $%.2f)", pod_id, status, session["hours"], session["cost"])
            if status == "done":
                r = requests.get(f"{base}/results.tar.gz", timeout=600)
                r.raise_for_status()
                with tarfile.open(fileobj=io.BytesIO(r.content)) as tf:
                    tf.extractall(ROOT / "results" / "runpod" / pod_id, filter="data")  # staged; merged by hand after review
                for name in ("run.log", "setup.log", "exit.txt"):
                    (ROOT / "results" / "runpod" / pod_id / name).write_text(requests.get(f"{base}/{name}", timeout=60).text, encoding="utf-8")
                session["outcome"] = "done"
                break
        else:
            session["outcome"] = f"timeout ({status})"
    finally:
        runpod.terminate_pod(pod_id)
        session["hours"] = (time.time() - t0) / 3600
        session["cost"] = session["hours"] * price
        if session["outcome"] == "running":
            session["outcome"] = "aborted"
        record(session)
        log.info("terminated pod %s: %.2f h, $%.2f; total spent $%.2f", pod_id, session["hours"], session["cost"], spent())


if __name__ == "__main__":
    main()
